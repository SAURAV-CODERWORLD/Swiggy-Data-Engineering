USE SCHEMA SANDBOX.CONSUMPTION_SCH;


-- ============================================================
-- 1. CREATE ORDER ITEM FACT TABLE
-- ============================================================

CREATE OR REPLACE TABLE CONSUMPTION_SCH.ORDER_ITEM_FACT (
    ORDER_ITEM_FACT_SK NUMBER AUTOINCREMENT
        COMMENT 'Surrogate Key (EDW)',

    ORDER_ITEM_ID NUMBER
        COMMENT 'Order Item ID from source system',

    ORDER_ID NUMBER
        COMMENT 'Order ID from source system',

    CUSTOMER_DIM_KEY NUMBER
        COMMENT 'Foreign key to CUSTOMER_DIM',

    CUSTOMER_ADDRESS_DIM_KEY NUMBER
        COMMENT 'Foreign key to CUSTOMER_ADDRESS_DIM',

    RESTAURANT_DIM_KEY NUMBER
        COMMENT 'Foreign key to RESTAURANT_DIM',

    RESTAURANT_LOCATION_DIM_KEY NUMBER
        COMMENT 'Foreign key to RESTAURANT_LOCATION_DIM',

    MENU_DIM_KEY NUMBER
        COMMENT 'Foreign key to MENU_DIM',

    DELIVERY_AGENT_DIM_KEY NUMBER
        COMMENT 'Foreign key to DELIVERY_AGENT_DIM',

    ORDER_DATE_DIM_KEY NUMBER
        COMMENT 'Foreign key to DATE_DIM',

    QUANTITY NUMBER
        COMMENT 'Order quantity',

    PRICE NUMBER(10,2)
        COMMENT 'Price per item',

    SUBTOTAL NUMBER(10,2)
        COMMENT 'Order item subtotal',

    DELIVERY_STATUS VARCHAR
        COMMENT 'Delivery status',

    ESTIMATED_TIME VARCHAR
        COMMENT 'Estimated delivery time'
)
COMMENT = 'Order item level fact table containing item, order, customer, restaurant, menu, delivery and date information';


-- ============================================================
-- 2. LOAD ORDER ITEM FACT
-- ============================================================

MERGE INTO CONSUMPTION_SCH.ORDER_ITEM_FACT AS TARGET

USING
(
    SELECT
        oi.ORDER_ITEM_ID AS ORDER_ITEM_ID,
        oi.ORDER_ID_FK AS ORDER_ID,

        c.CUSTOMER_HK AS CUSTOMER_DIM_KEY,

        ca.CUSTOMER_ADDRESS_HK AS CUSTOMER_ADDRESS_DIM_KEY,

        r.RESTAURANT_HK AS RESTAURANT_DIM_KEY,

        rl.RESTAURANT_LOCATION_HK AS RESTAURANT_LOCATION_DIM_KEY,

        m.MENU_DIM_HK AS MENU_DIM_KEY,

        da.DELIVERY_AGENT_HK AS DELIVERY_AGENT_DIM_KEY,

        dd.DATE_DIM_HK AS ORDER_DATE_DIM_KEY,

        oi.QUANTITY::NUMBER AS QUANTITY,

        oi.PRICE::NUMBER(10,2) AS PRICE,

        oi.SUBTOTAL::NUMBER(10,2) AS SUBTOTAL,

        d.DELIVERY_STATUS AS DELIVERY_STATUS,

        d.ESTIMATED_TIME AS ESTIMATED_TIME

    FROM SANDBOX.CLEAN_SCH.ORDER_ITEM AS oi

 INNER JOIN SANDBOX.CLEAN_SCH.ORDERS AS o
    ON oi.ORDER_ID_FK = o.ORDER_ID

LEFT JOIN SANDBOX.CLEAN_SCH.DELIVERY_ENTITY_TX AS d
    ON o.ORDER_ID = d.ORDER_ID

INNER JOIN SANDBOX.CONSUMPTION_SCH.CUSTOMER_DIM AS c
    ON o.CUSTOMER_ID_FK = c.CUSTOMER_ID
   AND c.IS_CURRENT = TRUE

LEFT JOIN SANDBOX.CONSUMPTION_SCH.CUSTOMER_ADDRESS_DIM AS ca
    ON c.CUSTOMER_ID = ca.CUSTOMER_ID_FK
   AND ca.PRIMARY_FLAG = TRUE
   AND ca.IS_CURRENT = TRUE

INNER JOIN SANDBOX.CONSUMPTION_SCH.RESTAURANT_DIM AS r
    ON o.RESTAURANT_ID_FK = r.RESTAURANT_ID
   AND r.IS_CURRENT = TRUE

INNER JOIN SANDBOX.CONSUMPTION_SCH.RESTAURANT_LOCATION_DIM AS rl
    ON r.LOCATION_ID_FK = rl.LOCATION_ID

INNER JOIN SANDBOX.CONSUMPTION_SCH.MENU_DIM AS m
    ON oi.MENU_ID_FK = m.MENU_ID
   AND m.IS_CURRENT = TRUE

LEFT JOIN SANDBOX.CONSUMPTION_SCH.DELIVERY_AGENT_DIM AS da
    ON d.DELIVERY_AGENT_ID = da.DELIVERY_AGENT_ID
   AND da.IS_CURRENT = TRUE

INNER JOIN SANDBOX.CONSUMPTION_SCH.DATE_DIM AS dd
    ON dd.CALENDAR_DATE = DATE(o.ORDER_DATE)

) AS SOURCE_STM

ON TARGET.ORDER_ITEM_ID = SOURCE_STM.ORDER_ITEM_ID
AND TARGET.ORDER_ID = SOURCE_STM.ORDER_ID


-- ============================================================
-- UPDATE EXISTING FACT RECORD
-- ============================================================

WHEN MATCHED THEN

    UPDATE SET

        TARGET.CUSTOMER_DIM_KEY =
            SOURCE_STM.CUSTOMER_DIM_KEY,

        TARGET.CUSTOMER_ADDRESS_DIM_KEY =
            SOURCE_STM.CUSTOMER_ADDRESS_DIM_KEY,

        TARGET.RESTAURANT_DIM_KEY =
            SOURCE_STM.RESTAURANT_DIM_KEY,

        TARGET.RESTAURANT_LOCATION_DIM_KEY =
            SOURCE_STM.RESTAURANT_LOCATION_DIM_KEY,

        TARGET.MENU_DIM_KEY =
            SOURCE_STM.MENU_DIM_KEY,

        TARGET.DELIVERY_AGENT_DIM_KEY =
            SOURCE_STM.DELIVERY_AGENT_DIM_KEY,

        TARGET.ORDER_DATE_DIM_KEY =
            SOURCE_STM.ORDER_DATE_DIM_KEY,

        TARGET.QUANTITY =
            SOURCE_STM.QUANTITY,

        TARGET.PRICE =
            SOURCE_STM.PRICE,

        TARGET.SUBTOTAL =
            SOURCE_STM.SUBTOTAL,

        TARGET.DELIVERY_STATUS =
            SOURCE_STM.DELIVERY_STATUS,

        TARGET.ESTIMATED_TIME =
            SOURCE_STM.ESTIMATED_TIME


-- ============================================================
-- INSERT NEW FACT RECORD
-- ============================================================

WHEN NOT MATCHED THEN

    INSERT
    (
        ORDER_ITEM_ID,
        ORDER_ID,
        CUSTOMER_DIM_KEY,
        CUSTOMER_ADDRESS_DIM_KEY,
        RESTAURANT_DIM_KEY,
        RESTAURANT_LOCATION_DIM_KEY,
        MENU_DIM_KEY,
        DELIVERY_AGENT_DIM_KEY,
        ORDER_DATE_DIM_KEY,
        QUANTITY,
        PRICE,
        SUBTOTAL,
        DELIVERY_STATUS,
        ESTIMATED_TIME
    )

    VALUES
    (
        SOURCE_STM.ORDER_ITEM_ID,
        SOURCE_STM.ORDER_ID,
        SOURCE_STM.CUSTOMER_DIM_KEY,
        SOURCE_STM.CUSTOMER_ADDRESS_DIM_KEY,
        SOURCE_STM.RESTAURANT_DIM_KEY,
        SOURCE_STM.RESTAURANT_LOCATION_DIM_KEY,
        SOURCE_STM.MENU_DIM_KEY,
        SOURCE_STM.DELIVERY_AGENT_DIM_KEY,
        SOURCE_STM.ORDER_DATE_DIM_KEY,
        SOURCE_STM.QUANTITY,
        SOURCE_STM.PRICE,
        SOURCE_STM.SUBTOTAL,
        SOURCE_STM.DELIVERY_STATUS,
        SOURCE_STM.ESTIMATED_TIME
    );


-- ============================================================
-- 3. FOREIGN KEY CONSTRAINTS
-- ============================================================

ALTER TABLE CONSUMPTION_SCH.ORDER_ITEM_FACT
    ADD CONSTRAINT FK_ORDER_ITEM_FACT_CUSTOMER_DIM
    FOREIGN KEY (CUSTOMER_DIM_KEY)
    REFERENCES CONSUMPTION_SCH.CUSTOMER_DIM (CUSTOMER_HK);


ALTER TABLE CONSUMPTION_SCH.ORDER_ITEM_FACT
    ADD CONSTRAINT FK_ORDER_ITEM_FACT_CUSTOMER_ADDRESS_DIM
    FOREIGN KEY (CUSTOMER_ADDRESS_DIM_KEY)
    REFERENCES CONSUMPTION_SCH.CUSTOMER_ADDRESS_DIM
        (CUSTOMER_ADDRESS_HK);


ALTER TABLE CONSUMPTION_SCH.ORDER_ITEM_FACT
    ADD CONSTRAINT FK_ORDER_ITEM_FACT_RESTAURANT_DIM
    FOREIGN KEY (RESTAURANT_DIM_KEY)
    REFERENCES CONSUMPTION_SCH.RESTAURANT_DIM
        (RESTAURANT_HK);


ALTER TABLE CONSUMPTION_SCH.ORDER_ITEM_FACT
    ADD CONSTRAINT FK_ORDER_ITEM_FACT_RESTAURANT_LOCATION_DIM
    FOREIGN KEY (RESTAURANT_LOCATION_DIM_KEY)
    REFERENCES CONSUMPTION_SCH.RESTAURANT_LOCATION_DIM
        (RESTAURANT_LOCATION_HK);


ALTER TABLE CONSUMPTION_SCH.ORDER_ITEM_FACT
    ADD CONSTRAINT FK_ORDER_ITEM_FACT_MENU_DIM
    FOREIGN KEY (MENU_DIM_KEY)
    REFERENCES CONSUMPTION_SCH.MENU_DIM
        (MENU_DIM_HK);


ALTER TABLE CONSUMPTION_SCH.ORDER_ITEM_FACT
    ADD CONSTRAINT FK_ORDER_ITEM_FACT_DELIVERY_AGENT_DIM
    FOREIGN KEY (DELIVERY_AGENT_DIM_KEY)
    REFERENCES CONSUMPTION_SCH.DELIVERY_AGENT_DIM
        (DELIVERY_AGENT_HK);


ALTER TABLE CONSUMPTION_SCH.ORDER_ITEM_FACT
    ADD CONSTRAINT FK_ORDER_ITEM_FACT_DATE_DIM
    FOREIGN KEY (ORDER_DATE_DIM_KEY)
    REFERENCES CONSUMPTION_SCH.DATE_DIM
        (DATE_DIM_HK);


-- ============================================================
-- 4. VALIDATION
-- ============================================================

SELECT
    COUNT(*) AS TOTAL_FACT_RECORDS,
    COUNT(DISTINCT ORDER_ITEM_ID) AS UNIQUE_ORDER_ITEMS,
    COUNT(DISTINCT ORDER_ID) AS UNIQUE_ORDERS
FROM CONSUMPTION_SCH.ORDER_ITEM_FACT;


SELECT *
FROM CONSUMPTION_SCH.ORDER_ITEM_FACT
ORDER BY ORDER_ITEM_FACT_SK
LIMIT 20;


-- Check duplicate order-item records
SELECT
    ORDER_ITEM_ID,
    ORDER_ID,
    COUNT(*) AS CNT
FROM CONSUMPTION_SCH.ORDER_ITEM_FACT
GROUP BY
    ORDER_ITEM_ID,
    ORDER_ID
HAVING COUNT(*) > 1;