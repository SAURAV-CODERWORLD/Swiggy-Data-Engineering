    _STG_FILE_LOAD_TS TIMESTAMP,
    _STG_FILE_MD5 STRING,
    _COPY_DATA_TS TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Clean customer address table';


-- ============================================================
-- 4. INITIAL STAGE -> CLEAN LOAD
-- ============================================================

MERGE INTO CLEAN_SCH.CUSTOMER_ADDRESS AS CLEAN
USING
(
    SELECT
        TRY_TO_NUMBER(ADDRESSID) AS ADDRESS_ID,
        TRY_TO_NUMBER(CUSTOMERID) AS CUSTOMER_ID_FK,
        FLATNO AS FLAT_NO,
        HOUSENO AS HOUSE_NO,
        FLOOR,
        BUILDING,
        LANDMARK,
        LOCALITY,
        CITY,
        STATE,
        PINCODE,
        COORDINATES,
        PRIMARYFLAG AS PRIMARY_FLAG,
        ADDRESSTYPE AS ADDRESS_TYPE,

        TRY_TO_TIMESTAMP_TZ(
            CREATEDDATE,
            'YYYY-MM-DD"T"HH24:MI:SS.FF6'
        ) AS CREATED_DATE,

        TRY_TO_TIMESTAMP_TZ(
            MODIFIEDDATE,
            'YYYY-MM-DD"T"HH24:MI:SS.FF6'
        ) AS MODIFIED_DATE,

        _STG_FILE_NAME,
        _STG_FILE_LOAD_TS,
        _STG_FILE_MD5,
        _COPY_DATA_TS

    FROM STAGE_SCH.CUSTOMER_ADDRESS
) AS STAGE

ON CLEAN.ADDRESS_ID = STAGE.ADDRESS_ID

WHEN MATCHED THEN
    UPDATE SET
        CLEAN.CUSTOMER_ID_FK = STAGE.CUSTOMER_ID_FK,
        CLEAN.FLAT_NO = STAGE.FLAT_NO,
        CLEAN.HOUSE_NO = STAGE.HOUSE_NO,
        CLEAN.FLOOR = STAGE.FLOOR,
        CLEAN.BUILDING = STAGE.BUILDING,
        CLEAN.LANDMARK = STAGE.LANDMARK,
        CLEAN.LOCALITY = STAGE.LOCALITY,
        CLEAN.CITY = STAGE.CITY,
        CLEAN.STATE = STAGE.STATE,
        CLEAN.PINCODE = STAGE.PINCODE,
        CLEAN.COORDINATES = STAGE.COORDINATES,
        CLEAN.PRIMARY_FLAG = STAGE.PRIMARY_FLAG,
        CLEAN.ADDRESS_TYPE = STAGE.ADDRESS_TYPE,
        CLEAN.CREATED_DATE = STAGE.CREATED_DATE,
        CLEAN.MODIFIED_DATE = STAGE.MODIFIED_DATE,
        CLEAN._STG_FILE_NAME = STAGE._STG_FILE_NAME,
        CLEAN._STG_FILE_LOAD_TS = STAGE._STG_FILE_LOAD_TS,
        CLEAN._STG_FILE_MD5 = STAGE._STG_FILE_MD5,
        CLEAN._COPY_DATA_TS = STAGE._COPY_DATA_TS

WHEN NOT MATCHED THEN
    INSERT
    (
        ADDRESS_ID,
        CUSTOMER_ID_FK,
        FLAT_NO,
        HOUSE_NO,
        FLOOR,
        BUILDING,
        LANDMARK,
        LOCALITY,
        CITY,
        STATE,
        PINCODE,
        COORDINATES,
        PRIMARY_FLAG,
        ADDRESS_TYPE,
        CREATED_DATE,
        MODIFIED_DATE,
        _STG_FILE_NAME,
        _STG_FILE_LOAD_TS,
        _STG_FILE_MD5,
        _COPY_DATA_TS
    )
    VALUES
    (
        STAGE.ADDRESS_ID,
        STAGE.CUSTOMER_ID_FK,
        STAGE.FLAT_NO,
        STAGE.HOUSE_NO,
        STAGE.FLOOR,
        STAGE.BUILDING,
        STAGE.LANDMARK,
        STAGE.LOCALITY,
        STAGE.CITY,
        STAGE.STATE,
        STAGE.PINCODE,
        STAGE.COORDINATES,
        STAGE.PRIMARY_FLAG,
        STAGE.ADDRESS_TYPE,
        STAGE.CREATED_DATE,
        STAGE.MODIFIED_DATE,
        STAGE._STG_FILE_NAME,
        STAGE._STG_FILE_LOAD_TS,
        STAGE._STG_FILE_MD5,
        STAGE._COPY_DATA_TS
    );


